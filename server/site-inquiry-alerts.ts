/**
 * Alertas de mensagens recebidas pelo formulário do site.
 * Cada mensagem vira: (1) tarefa no Kanban para o responsável, (2) notificação no sininho
 * de toda a equipe e (3) e-mail para a equipe — para nenhum contato ficar sem resposta.
 */
import { db } from "./db";
import { storage } from "./storage";
import { sendEmail, baseLayout } from "./email";
import { todoistNotifications, todoistTasks, todoistComments, users } from "@shared/schema";
import { and, eq, gte, isNull, ne, sql } from "drizzle-orm";

const TASK_PREFIX = "📩 Responder contato do site";

const esc = (s: unknown) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]!));

function brToday(): Date {
  // data de hoje no horário de Brasília, gravada ao meio-dia UTC (padrão das demais tarefas)
  const br = new Date(Date.now() - 3 * 60 * 60 * 1000);
  return new Date(Date.UTC(br.getUTCFullYear(), br.getUTCMonth(), br.getUTCDate(), 12, 0, 0));
}

function siteBaseUrl(): string {
  if (process.env.CRM_URL) return process.env.CRM_URL.replace(/\/admin\/?$/, "");
  if (process.env.RAILWAY_PUBLIC_DOMAIN) return `https://${process.env.RAILWAY_PUBLIC_DOMAIN}`;
  return "https://monteiroseguros.com.br";
}

function row(label: string, value: string) {
  return `<tr><td style="padding:8px 0;color:#64748B;font-size:13px;width:120px;vertical-align:top;">${label}</td><td style="padding:8px 0;color:#0F172A;font-size:14px;font-weight:600;">${value}</td></tr>`;
}

export async function alertSiteInquiry(params: {
  contactId: number;
  name: string;
  email?: string | null;
  phone?: string | null;
  message: string;
  responsibleId: number;
}): Promise<void> {
  const { contactId, name, email, phone, message, responsibleId } = params;

  const team = (await db.select({ id: users.id, name: users.name, email: users.email, role: users.role }).from(users))
    .filter((u) => ["admin", "employee"].includes(String(u.role || "").toLowerCase()));

  // ---- 1. Tarefa no Kanban (uma por contato enquanto estiver em aberto) ----
  const [openTask] = await db
    .select()
    .from(todoistTasks)
    .where(
      and(
        eq(todoistTasks.contactId, contactId),
        eq(todoistTasks.autoGeneratedBy, "site_inquiry"),
        isNull(todoistTasks.deletedAt),
        ne(todoistTasks.status, "done"),
        ne(todoistTasks.status, "cancelled"),
      ),
    )
    .limit(1);

  const details = [
    `Mensagem enviada pelo formulário do site:`,
    `"${message}"`,
    "",
    phone ? `Telefone/WhatsApp: ${phone}` : null,
    email ? `E-mail: ${email}` : null,
  ].filter((l) => l !== null).join("\n");

  let taskId: number;
  if (openTask) {
    // Mesma pessoa mandou outra mensagem: registra na tarefa que já existe
    taskId = openTask.id;
    await db.insert(todoistComments).values({ taskId, userId: responsibleId, content: `Nova mensagem pelo site: "${message}"` });
    await db.update(todoistTasks).set({ updatedAt: new Date() }).where(eq(todoistTasks.id, taskId));
  } else {
    const task = await storage.createTodoistTask({
      title: `${TASK_PREFIX}: ${name}`,
      description: details,
      priority: "P1",
      status: "todo",
      kanbanColumn: "a_fazer",
      dueDate: brToday(),
      assignedTo: responsibleId,
      createdBy: responsibleId,
      contactId,
      autoGeneratedBy: "site_inquiry",
    } as any);
    taskId = task.id;
  }

  // ---- 2. Sininho para toda a equipe ----
  const excerpt = message.length > 140 ? message.slice(0, 137) + "..." : message;
  if (team.length) {
    await db.insert(todoistNotifications).values(
      team.map((u) => ({
        userId: u.id,
        taskId,
        title: "📩 Nova mensagem pelo site",
        message: `${name}${phone ? ` (${phone})` : ""}: ${excerpt}`,
        type: "site_inquiry",
      })),
    );
  }

  // ---- 3. E-mail (no máximo 1 por contato a cada 10 minutos, contra envios repetidos) ----
  const [recent] = await db
    .select({ n: sql<number>`count(*)` })
    .from(todoistNotifications)
    .where(
      and(
        eq(todoistNotifications.type, "site_inquiry"),
        eq(todoistNotifications.taskId, taskId),
        gte(todoistNotifications.createdAt, sql`localtimestamp - interval '10 minutes'`),
      ),
    );
  const alreadyEmailed = Number(recent?.n || 0) > team.length; // as notificações desta mensagem acabaram de ser criadas
  if (alreadyEmailed) return;

  const configured = (process.env.INQUIRY_NOTIFY_EMAILS || "")
    .split(/[,;\s]+/)
    .map((e) => e.trim())
    .filter((e) => e.includes("@"));
  const recipients = Array.from(
    new Set(configured.length ? configured : team.map((u) => (u.email || "").trim().toLowerCase()).filter((e) => e.includes("@"))),
  );
  if (!recipients.length) return;

  const cleanPhone = (phone || "").replace(/\D/g, "");
  const waUrl = cleanPhone ? `https://wa.me/${cleanPhone.startsWith("55") ? cleanPhone : "55" + cleanPhone}` : "";
  const responsible = team.find((u) => u.id === responsibleId);

  const html = baseLayout({
    title: "Nova mensagem pelo site",
    badge: "Contato do site",
    content: `
      <p style="color:#334155;font-size:15px;line-height:1.6;margin:0 0 20px;">
        Alguém acabou de enviar uma mensagem pelo formulário do site. Uma tarefa foi criada no Kanban${responsible ? ` para <strong>${esc(responsible.name)}</strong>` : ""}.
      </p>
      <div style="background:#F8FAFC;border:1px solid #E2E8F0;border-radius:16px;padding:20px;margin-bottom:20px;">
        <table width="100%" cellpadding="0" cellspacing="0">
          ${row("Nome", esc(name))}
          ${row("WhatsApp", waUrl ? `<a href="${waUrl}" style="color:#059669;text-decoration:none;">${esc(phone)} 💬</a>` : esc(phone || "Não informado"))}
          ${row("E-mail", email ? `<a href="mailto:${esc(email)}" style="color:#08454C;text-decoration:none;">${esc(email)}</a>` : "Não informado")}
        </table>
      </div>
      <div style="border-left:4px solid #C65F54;padding:12px 16px;background:#FFF7F5;border-radius:8px;color:#1E293B;font-size:15px;line-height:1.6;white-space:pre-wrap;">${esc(message)}</div>`,
    buttonUrl: `${siteBaseUrl()}/admin/todoist`,
    buttonText: "Abrir tarefa no CRM",
  });

  for (const to of recipients) {
    const r = await sendEmail({ to, subject: `📩 Nova mensagem pelo site: ${name}`, html });
    if (!r.success) console.error(`[site-inquiry] Falha ao enviar e-mail para ${to}: ${r.error}`);
  }
}
